const storedLocale = (() => {
  try {
    return localStorage.getItem('alubassa-locale') === 'en' ? 'en' : 'fr'
  } catch (error) {
    return 'fr'
  }
})()

export const locale = ref(storedLocale)

export function setLocale(value) {
  locale.value = value === 'en' ? 'en' : 'fr'
  try {
    localStorage.setItem('alubassa-locale', locale.value)
  } catch (error) {}
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale.value
    document.title = locale.value === 'en'
      ? 'Alubassa – Pure aluminium, made in Cameroon'
      : 'Alubassa – Aluminium pur, fabriqué au Cameroun'
  }
}

if (typeof document !== 'undefined') setLocale(storedLocale)

export function t(text) {
  if (typeof text !== 'string' || locale.value === 'fr') return text
  return translations[text] || text
}
